-- Reference DDL for a new, empty PostgreSQL 16 database.
-- Spring Boot does not execute this file; its existing Hibernate update and schema.sql remain in use.
CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name varchar(255)
);

CREATE TABLE friendship (
    id uuid PRIMARY KEY,
    created_time timestamp(6) without time zone,
    updated_time timestamp(6) without time zone,
    status varchar(255) NOT NULL,
    receiver_id bigint NOT NULL,
    requester_id bigint NOT NULL,
    requested_at timestamp(6) without time zone,
    approved_at timestamp(6) without time zone,
    CONSTRAINT friendship_status_check
        CHECK (status IN ('REQUESTED', 'ACCEPTED', 'REJECTED', 'BLOCKED')),
    CONSTRAINT friendship_requester_id_receiver_id_key UNIQUE (requester_id, receiver_id),
    CONSTRAINT fk_friendship_receiver FOREIGN KEY (receiver_id) REFERENCES users (user_id),
    CONSTRAINT fk_friendship_requester FOREIGN KEY (requester_id) REFERENCES users (user_id)
);

CREATE UNIQUE INDEX ux_friendship_active_pair
    ON friendship (LEAST(requester_id, receiver_id), GREATEST(requester_id, receiver_id))
    WHERE status IN ('REQUESTED', 'ACCEPTED');
